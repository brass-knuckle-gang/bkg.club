"""Hand-drawn pixel grids for Brass Knuckles Knock Out, read by spritegen.py.

Each letter is a material; the generator shades it (lit from the upper left) and outlines
every sprite. Lowercase letters are shaded automatically, uppercase ones are forced into
shadow, and digits force a highlight:

    s skin   h hair   t top   k trunks   g glove (your brass)   w white   a accent
    e gear   o ink (outline color, for lines inside a sprite)   . clear
    1 skin highlight   2 glove highlight   3 hair highlight

A grid given as `half(...)` is the left half of a symmetric sprite; the right half is its
mirror. Pivot comments give the pivot as (column, row).
"""


def half(*rows):
    """A symmetric grid from its left halves, each written to end at the middle."""
    w = max(len(r) for r in rows)
    rows = [r.rjust(w, ".") for r in rows]
    return [r + r[::-1] for r in rows]


def place(rows, left=0):
    """Rows shifted right by `left` columns."""
    return ["." * left + r for r in rows]


